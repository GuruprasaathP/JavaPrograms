package com.java.practice.pro.Day2;

public class StringMethodsPart1 {
    public static void main(String[] args) {
        String S1 = " Guruprasaath";
        String S2 = " Guruprasaath";

        System.out.println(S1.concat(" vidhya"));     // Concatenate
        System.out.println(S1.equals(S2));            // Exact match
        System.out.println(S1.equalsIgnoreCase(S2));  // Match ignoring case
    }
}
